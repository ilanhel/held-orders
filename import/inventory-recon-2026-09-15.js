const norm = (s) => s.replace(/×/g, 'x').replace(/\s+/g, ' ').trim()

async function main() {
  const products = await prisma.product.findMany({
    include: { category: { select: { name: true } } },
  })
  const aliases = await prisma.productBarcodeAlias.findMany()
  const byBarcode = new Map(products.map((p) => [p.barcode, p]))
  const byAlias = new Map(aliases.map((a) => [a.barcode, a.productId]))
  const byId = new Map(products.map((p) => [p.id, p]))
  const byInvoice = new Map()
  for (const p of products) {
    if (p.invoiceBarcode) {
      const list = byInvoice.get(p.invoiceBarcode) ?? []
      list.push(p)
      byInvoice.set(p.invoiceBarcode, list)
    }
  }

  const seen = new Set()
  const results = { exact: [], viaInvoice: [], badBarcode: [], unknown: [], dupLines: [] }
  for (const [barcode, name, qty] of INVENTORY) {
    const key = barcode + '|' + name
    if (seen.has(key)) { results.dupLines.push([barcode, name]); continue }
    seen.add(key)

    const validEan = /^\d{12,13}$/.test(barcode)
    const direct = byBarcode.get(barcode) ?? (byAlias.has(barcode) ? byId.get(byAlias.get(barcode)) : null)
    const invoiceHits = byInvoice.get(barcode) ?? []

    if (direct) {
      results.exact.push({ barcode, name, qty, product: direct })
    } else if (invoiceHits.length > 0) {
      results.viaInvoice.push({ barcode, name, qty, hits: invoiceHits })
    } else if (!validEan) {
      results.badBarcode.push({ barcode, name, qty })
    } else {
      results.unknown.push({ barcode, name, qty })
    }
  }

  console.log('== duplicate inventory lines (same barcode+name):', results.dupLines.length)
  for (const [b, n] of results.dupLines) console.log('   ', b, n)

  console.log('\n== EXACT barcode matches:', results.exact.length)
  for (const r of results.exact) {
    console.log(`   ${r.barcode} | "${norm(r.name)}" -> [${r.product.status}] "${r.product.name}" (cat ${r.product.category.name}${r.product.groupName ? ', grp ' + r.product.groupName : ''})`)
  }

  console.log('\n== matched via invoiceBarcode (group billing SKU):', results.viaInvoice.length)
  for (const r of results.viaInvoice) {
    console.log(`   ${r.barcode} | "${norm(r.name)}" -> bills: ${r.hits.map((h) => `[${h.status}] ${h.name}`).join(' | ')}`)
  }

  console.log('\n== SUSPICIOUS barcodes (not 12-13 digits):', results.badBarcode.length)
  for (const r of results.badBarcode) console.log(`   ${r.barcode} (${r.barcode.length} ספרות) | ${norm(r.name)}`)

  console.log('\n== UNKNOWN barcodes (valid EAN, not in catalog):', results.unknown.length)
  for (const r of results.unknown) console.log(`   ${r.barcode} | ${norm(r.name)}`)

  // Products in albums+frames categories NOT covered by any inventory barcode
  const invBarcodes = new Set(INVENTORY.map(([b]) => b))
  const inScope = products.filter(
    (p) => (p.category.name === 'אלבומים' || p.category.name === 'מסגרות') && p.status !== 'HIDDEN'
  )
  const uncovered = inScope.filter((p) => {
    if (invBarcodes.has(p.barcode)) return false
    if (p.invoiceBarcode && invBarcodes.has(p.invoiceBarcode)) return false
    const productAliases = aliases.filter((a) => a.productId === p.id)
    return !productAliases.some((a) => invBarcodes.has(a.barcode))
  })
  console.log('\n== ACTIVE products in אלבומים/מסגרות NOT in the inventory list:', uncovered.length)
  for (const p of uncovered) console.log(`   [${p.category.name}] ${p.barcode.padEnd(14)} | ${p.name}${p.groupName ? ' (grp ' + p.groupName + ')' : ''}`)
}

main()
  .catch((e) => { console.error(e); process.exit(1) })
  .finally(() => prisma.$disconnect())
